export function calculateCoordDistance(
  coord1: { x: number; y: number },
  coord2: { x: number; y: number }
): number {
  const dx = coord1.x - coord2.x;
  const dy = coord1.y - coord2.y;
  return Number(Math.sqrt(dx * dx + dy * dy).toFixed(2));
}
